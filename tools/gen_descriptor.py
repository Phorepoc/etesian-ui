"""gen_descriptor -- maintainer tool: writes skin/etesian-dark.txt.

The skin descriptor's colour tables are positional (EAknsCIQsn*ColorsCGn = row n), so the *row counts* come from a reference
descriptor of the 2010 release (Haze, EPL: only the structure is read) and every VALUE is ours: a role map from the reference's
colours onto the Etesian dark-mode tokens (design/tokens/tokens.json, AGPL-3.0-only):
  white text/lines/icons -> #FFFFFF; greys -> secondary #C8C8C8 / disabled #8C8C8C; dark text on light -> #282828;
  the reference's accent colours (teals/blues) -> the Etesian default accent #4591FF; red -> warning #DA201E; gold -> #CC9900.
    python3 gen_descriptor.py <path to haze.txt> > skin/etesian-dark.txt
"""
import re, sys

FG, FG2, DIS, ACC = 0xFFFFFF, 0xC8C8C8, 0x8C8C8C, 0x4591FF
def lum(c): r, g, b = c >> 16, c >> 8 & 255, c & 255; return (r * 3 + g * 6 + b) // 10
def hue_accent(c):
    r, g, b = c >> 16, c >> 8 & 255, c & 255
    return max(r, g, b) - min(r, g, b) > 60
def mapc(c):
    if c == 0xFFFFFF: return FG
    if c == 0x000000: return 0x000000
    if hue_accent(c):
        if c == 0xF08080 or c == 0xFF9999 or c == 0xFF0066: return 0xDA201E
        if c == 0xFFD700: return 0xCC9900
        return ACC
    l = lum(c)
    if l < 40: return 0x282828
    if l > 170: return FG2
    return DIS

def main(ref):
    raw = open(ref, 'rb').read()
    txt = raw.decode('utf-16' if raw[:2] in (b'\xff\xfe', b'\xfe\xff') else 'latin-1').replace('\r', '')
    out = []
    for m in re.finditer(r'COLORTABLE IID=(\w+)\n((?:\s*RGB=0x[0-9a-fA-F]+\n)+)', txt):
        rows = [int(x, 16) for x in re.findall(r'RGB=(0x[0-9a-fA-F]+)', m.group(2))]
        out.append('COLORTABLE IID=%s\n%s' % (m.group(1), ''.join('\tRGB=0x%06x\n' % mapc(r) for r in rows) + 'END\n\n'))

    print(HEADER + ''.join(out) + FOOTER)

HEADER = '''// Etesian Dark -- a Phorepoc skin (AGPL-3.0-only). Generated by tools/gen_descriptor.py; edit that, not this.
// Tokens: Etesian design language (AGPL-3.0-only), https://github.com/etesian-design/design
SKINTYPE scalable
UID 0xE7016B31
NAME 1 "Etesian"
AUTHOR "Phorepoc"
COPYRIGHT "AGPL-3.0-only; Etesian, founded by Kyriakos Bompotis"
STRING IID=PropertyListSeparatorLines "false"
'''
def bg(iid, f):
    return ('SCALABLEITEM IID=%s INPUT=none OUTPUT=0/RGB\n\tEFFECT UID=0x101F8748 INPUTA=none INPUTB=none OUTPUT=0/RGBA\n'
            '\t\t\tBMP f c16 %s SOFTMASK\n\t\t\tINT ms 0\n\t\tEND\nEND\n' % (iid, f))
FOOTER = '\n' + ''.join([bg('QsnBgScreen', 'qsn_bg_screen.svg'), bg('QsnBgScreenMp', 'qsn_bg_screen.svg')]
    + [bg(i, 'qsn_bg_area_status.svg') for i in ('QsnBgAreaStaconRt', 'QsnBgAreaStaconLt', 'QsnBgAreaStaconLb', 'QsnBgAreaStaconRb')])
main(sys.argv[1])
